import { NextResponse, type NextRequest } from "next/server";
import type { EmailOtpType } from "@supabase/supabase-js";
import { createClient } from "@/lib/supabase/server";

/**
 * Bestätigt den E-Mail-Link aus dem Profil-Claim (und künftige Magic-Links).
 * Supabase-Mail-Template muss auf
 *   {{ .SiteURL }}/auth/confirm?token_hash={{ .TokenHash }}&type=email_change&next=/me
 * zeigen.
 */
export async function GET(request: NextRequest) {
  const { searchParams, origin } = new URL(request.url);
  const token_hash = searchParams.get("token_hash");
  const type = searchParams.get("type") as EmailOtpType | null;
  const next = searchParams.get("next") ?? "/me?claimed=1";

  if (token_hash && type) {
    const supabase = await createClient();
    const { error } = await supabase.auth.verifyOtp({ type, token_hash });
    if (!error) {
      return NextResponse.redirect(`${origin}${next}`);
    }
  }

  return NextResponse.redirect(`${origin}/me?claim_error=1`);
}
